def format_prompt(template: str, data: dict) -> str:
    """
    Форматирует промпт с данными события.

    Args:
        template: Шаблон промпта
        data: Данные для подстановки

    Returns:
        str: Отформатированный промпт

    Example:
        >>> data = {'amount_usd': 5000000, 'symbol': 'BTC'}
        >>> prompt = format_prompt(WHALE_ALERT_PROMPT, data)
        >>> 'BTC' in prompt
        True
    """
    try:
        return template.format(**data)
    except KeyError as e:
        # Если не хватает данных, возвращаем промпт с доступными данными
        # Используем safe_substitute через словарь
        import string
        return string.Template(template).safe_substitute(**data)
