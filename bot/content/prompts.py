"""
Промпты для генерации аналитического контента через Claude AI
"""
import random

# 10 разных шаблонов для постов с разным оформлением
POST_TEMPLATES = [
    # Шаблон 1: Классический с подзаголовком
    """🔴 **{flag} ЗАГОЛОВОК**

_{subtitle}_

{main_text}

💬 {opinion}

[📰 Источник]({source_url})""",

    # Шаблон 2: С цитатой в начале
    """*"{quote}"*

{flag} {main_text}

**Мнение автора:** {opinion}

→ [Подробнее на {source_name}]({source_url})""",

    # Шаблон 3: С эмодзи-разделителями
    """⚡️ {flag} **{headline}**

{main_text}

━━━━━━━━━━━━━━
💭 {opinion}

🔗 [Читать полностью]({source_url})""",

    # Шаблон 4: Лаконичный стиль
    """{flag} {main_text}

_{opinion}_

📎 [{source_name}]({source_url})""",

    # Шаблон 5: С блоками данных
    """📌 {flag} **{headline}**

```
{data_block}
```

{main_text}

**Вывод:** {opinion}

🔗 [Источник]({source_url})""",

    # Шаблон 6: Стиль "молнии"
    """⚡️⚡️⚡️

{flag} **{headline}**

{main_text}

💬 *{opinion}*

⚡️⚡️⚡️

📰 [Детали]({source_url})""",

    # Шаблон 7: С нумерованным списком
    """{flag} **{headline}**

{numbered_list}

💡 {opinion}

→ [Источник: {source_name}]({source_url})""",

    # Шаблон 8: Стиль "Breaking News"
    """🔴 BREAKING NEWS

{flag} {main_text}

━━━━━━━━━━━━━━
**Комментарий:** _{opinion}_

[📱 Читать в источнике]({source_url})""",

    # Шаблон 9: С подчеркиванием ключевых слов
    """{flag} {main_text_with_underlines}

**Что это значит?**
{opinion}

🔗 [Полная версия]({source_url})""",

    # Шаблон 10: Минималистичный
    """**{headline}** {flag}

{main_text}

_{opinion}_

[→ {source_name}]({source_url})"""
]

def get_random_template():
    """Получить случайный шаблон"""
    template_num = random.randint(1, len(POST_TEMPLATES))
    template = POST_TEMPLATES[template_num - 1]
    return template_num, template

